CREATE OR REPLACE FUNCTION public.listar_meus_emprestimos(p_usuario_id bigint)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    resultado json;
begin
    select coalesce(json_agg(row_to_json(t)), '[]'::json) into resultado
    from (
        select
            e.id, e.livro_id, e.data_emprestimo, e.data_prevista_devolucao, e.data_devolucao_real,
            e.status, e.renovacoes_restantes,
            json_build_object('id', l.id, 'titulo', l.titulo, 'autor', l.autor, 'categoria', l.categoria, 'capa_url', l.capa_url) as livro
        from emprestimos e
        join livros l on l.id = e.livro_id
        where e.usuario_id = p_usuario_id
        order by e.data_emprestimo desc
    ) t;
    return resultado;
end;
