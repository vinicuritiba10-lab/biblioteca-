-- Quantos títulos cada categoria tem (cards da página inicial)
create or replace function public.contagem_categorias()
 returns json
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
    resultado json;
begin
    select coalesce(json_agg(row_to_json(t)), '[]'::json) into resultado
    from (
        select lower(categoria) as categoria, count(*)::int as total
        from livros
        where coalesce(categoria, '') <> ''
        group by lower(categoria)
        order by total desc
    ) t;
    return resultado;
end;
$function$;


-- { "livro_id": { "media": 4.5, "total": 3 } } para as estrelas nos cards
create or replace function public.medias_avaliacoes()
 returns json
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
    resultado json;
begin
    select coalesce(json_object_agg(t.livro_id, json_build_object('media', t.media, 'total', t.total)), '{}'::json)
        into resultado
    from (
        select livro_id, round(avg(nota)::numeric, 1) as media, count(*)::int as total
        from avaliacoes
        group by livro_id
    ) t;
    return resultado;
end;
$function$;


-- Vitrines: recomendados, mais emprestados, mais bem avaliados e novidades
create or replace function public.destaques_livros(p_usuario_id bigint)
 returns json
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
    limite constant int := 8;
    v_mais_emprestados json;
    v_bem_avaliados json;
    v_novidades json;
    v_recomendados json := '[]'::json;
    v_motivo text;
begin
    select coalesce(json_agg(row_to_json(t)), '[]'::json) into v_mais_emprestados
    from (
        select l.*, count(e.id)::int as total_emprestimos
        from livros l
        join emprestimos e on e.livro_id = l.id
        group by l.id
        order by total_emprestimos desc, l.titulo asc
        limit limite
    ) t;

    select coalesce(json_agg(row_to_json(t)), '[]'::json) into v_bem_avaliados
    from (
        select l.*, round(avg(a.nota)::numeric, 1) as media, count(a.id)::int as total_avaliacoes
        from livros l
        join avaliacoes a on a.livro_id = l.id
        group by l.id
        order by media desc, total_avaliacoes desc, l.titulo asc
        limit limite
    ) t;

    select coalesce(json_agg(row_to_json(t)), '[]'::json) into v_novidades
    from (
        select l.* from livros l order by l.id desc limit limite
    ) t;

    if p_usuario_id is not null then
        -- livros das categorias que o aluno mais lê e que ele ainda não pegou
        select coalesce(json_agg(row_to_json(t)), '[]'::json) into v_recomendados
        from (
            with categorias_do_aluno as (
                select lower(l.categoria) as categoria, count(*) as peso
                from emprestimos e
                join livros l on l.id = e.livro_id
                where e.usuario_id = p_usuario_id and coalesce(l.categoria, '') <> ''
                group by lower(l.categoria)
            ),
            popularidade as (
                select livro_id, count(*) as total from emprestimos group by livro_id
            )
            select l.*, coalesce(p.total, 0)::int as total_emprestimos
            from livros l
            join categorias_do_aluno c on lower(l.categoria) = c.categoria
            left join popularidade p on p.livro_id = l.id
            where l.id not in (select livro_id from emprestimos where usuario_id = p_usuario_id)
            order by c.peso desc, (l.quantidade_disponivel > 0) desc, coalesce(p.total, 0) desc, l.titulo asc
            limit limite
        ) t;
        v_motivo := 'Com base nas categorias que você mais lê';

        -- sem histórico: os mais populares que o aluno ainda não leu
        if json_array_length(v_recomendados) = 0 then
            select coalesce(json_agg(row_to_json(t)), '[]'::json) into v_recomendados
            from (
                select l.*, count(e.id)::int as total_emprestimos
                from livros l
                left join emprestimos e on e.livro_id = l.id
                where l.id not in (select livro_id from emprestimos where usuario_id = p_usuario_id)
                group by l.id
                order by (l.quantidade_disponivel > 0) desc, total_emprestimos desc, l.id desc
                limit limite
            ) t;
            v_motivo := 'Populares que você ainda não leu';
        end if;
    end if;

    return json_build_object(
        'recomendados', json_build_object('motivo', v_motivo, 'livros', v_recomendados),
        'mais_emprestados', v_mais_emprestados,
        'bem_avaliados', v_bem_avaliados,
        'novidades', v_novidades
    );
end;
$function$;


-- Ficha completa de um livro, com a situação do aluno que está vendo
create or replace function public.detalhes_livro(p_usuario_id bigint, p_livro_id bigint)
 returns json
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
    liv livros;
    v_media numeric;
    v_total int;
    v_distribuicao json;
    v_recentes json;
    v_fila int;
    v_total_emprestimos int;
    v_usuario json;
begin
    select * into liv from livros where id = p_livro_id;
    if liv.id is null then
        raise exception 'Livro não encontrado.';
    end if;

    select round(avg(nota)::numeric, 1), count(*)::int into v_media, v_total
        from avaliacoes where livro_id = p_livro_id;

    select json_agg(json_build_object(
                'nota', n,
                'total', (select count(*) from avaliacoes where livro_id = p_livro_id and nota = n)
            ) order by n desc)
        into v_distribuicao
        from generate_series(1, 5) as n;

    select coalesce(json_agg(row_to_json(t)), '[]'::json) into v_recentes
    from (
        select a.id, a.usuario_id, coalesce(u.nome, 'Aluno') as nome, a.nota, a.comentario, a.data_avaliacao
        from avaliacoes a
        left join usuarios u on u.id = a.usuario_id
        where a.livro_id = p_livro_id
        order by a.data_avaliacao desc
        limit 20
    ) t;

    select count(*) into v_fila from reservas where livro_id = p_livro_id and status = 'ativa';
    select count(*) into v_total_emprestimos from emprestimos where livro_id = p_livro_id;

    if p_usuario_id is not null then
        v_usuario := json_build_object(
            'favorito', exists (select 1 from favoritos where usuario_id = p_usuario_id and livro_id = p_livro_id),
            'pode_avaliar', exists (select 1 from emprestimos where usuario_id = p_usuario_id and livro_id = p_livro_id),
            'minha_avaliacao', (
                select row_to_json(x) from (
                    select id, nota, comentario from avaliacoes
                    where usuario_id = p_usuario_id and livro_id = p_livro_id
                ) x
            ),
            'emprestimo_ativo', (
                select row_to_json(x) from (
                    select id, data_prevista_devolucao from emprestimos
                    where usuario_id = p_usuario_id and livro_id = p_livro_id and status = 'ativo'
                    limit 1
                ) x
            ),
            'reserva', (
                select row_to_json(x) from (
                    select id, status, data_disponivel from reservas
                    where usuario_id = p_usuario_id and livro_id = p_livro_id and status in ('ativa', 'disponivel')
                    limit 1
                ) x
            )
        );
    end if;

    return json_build_object(
        'livro', row_to_json(liv),
        'total_emprestimos', v_total_emprestimos,
        'fila_reservas', v_fila,
        'avaliacoes', json_build_object(
            'media', v_media,
            'total', v_total,
            'distribuicao', v_distribuicao,
            'recentes', v_recentes
        ),
        'usuario', v_usuario
    );
end;
$function$;


-- Cria ou atualiza a avaliação do aluno. Só avalia quem já pegou o livro.
create or replace function public.avaliar_livro(p_usuario_id bigint, p_livro_id bigint, p_nota integer, p_comentario text)
 returns json
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
    liv livros;
    v_comentario text;
    v_ja_existia boolean;
begin
    if p_nota is null or p_nota < 1 or p_nota > 5 then
        raise exception 'A nota deve ser de 1 a 5.';
    end if;

    select * into liv from livros where id = p_livro_id;
    if liv.id is null then
        raise exception 'Livro não encontrado.';
    end if;

    if not exists (select 1 from emprestimos where usuario_id = p_usuario_id and livro_id = p_livro_id) then
        raise exception 'Você só pode avaliar livros que já pegou emprestado.';
    end if;

    v_comentario := nullif(left(trim(coalesce(p_comentario, '')), 500), '');
    v_ja_existia := exists (select 1 from avaliacoes where usuario_id = p_usuario_id and livro_id = p_livro_id);

    insert into avaliacoes (usuario_id, livro_id, nota, comentario)
    values (p_usuario_id, p_livro_id, p_nota, v_comentario)
    on conflict (usuario_id, livro_id)
    do update set nota = excluded.nota, comentario = excluded.comentario, data_avaliacao = now();

    perform registrar_log(p_usuario_id, 'Livro avaliado', format('%s (%s de 5)', liv.titulo, p_nota));

    return json_build_object(
        'message', case when v_ja_existia then 'Avaliação atualizada.' else 'Obrigado pela avaliação!' end
    );
end;
$function$;


-- Apaga uma avaliação (a própria, ou qualquer uma se for da biblioteca)
create or replace function public.apagar_avaliacao(p_usuario_id bigint, p_avaliacao_id bigint)
 returns json
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
    av avaliacoes;
begin
    select * into av from avaliacoes where id = p_avaliacao_id;
    if av.id is null then
        raise exception 'Avaliação não encontrada.';
    end if;
    if av.usuario_id <> p_usuario_id and not eh_bibliotecario(p_usuario_id) then
        raise exception 'Você só pode apagar a sua própria avaliação.';
    end if;

    delete from avaliacoes where id = p_avaliacao_id;

    return json_build_object('message', 'Avaliação apagada.');
end;
$function$;


