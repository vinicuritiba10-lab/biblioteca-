-- Minha Conta: resumo de leitura, próxima devolução, suspensão e histórico.
-- As conquistas são calculadas no navegador a partir do "resumo" (TR/logica.js).
create or replace function public.perfil_usuario(p_usuario_id bigint)
 returns json
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
    u usuarios;
    hoje date := libro_hoje();
    v_total int;
    v_lidos int;
    v_ativos int;
    v_atrasados int;
    v_no_prazo int;
    v_devolvidos_com_data int;
    v_categorias int;
    v_categoria_favorita text;
    v_avaliacoes int;
    v_favoritos int;
    v_proxima json;
    v_suspensao json;
    v_historico json;
begin
    select * into u from usuarios where id = p_usuario_id;
    if u.id is null then
        raise exception 'Usuário não encontrado.';
    end if;

    select
        count(*),
        count(*) filter (where status = 'devolvido'),
        count(*) filter (where status = 'ativo'),
        count(*) filter (where status = 'ativo' and libro_data_local(data_prevista_devolucao) < hoje),
        count(*) filter (where status = 'devolvido' and data_devolucao_real is not null
                         and libro_data_local(data_devolucao_real) <= libro_data_local(data_prevista_devolucao)),
        count(*) filter (where status = 'devolvido' and data_devolucao_real is not null)
    into v_total, v_lidos, v_ativos, v_atrasados, v_no_prazo, v_devolvidos_com_data
    from emprestimos
    where usuario_id = p_usuario_id;

    select count(distinct lower(l.categoria)) into v_categorias
    from emprestimos e
    join livros l on l.id = e.livro_id
    where e.usuario_id = p_usuario_id and coalesce(l.categoria, '') <> '';

    select lower(l.categoria) into v_categoria_favorita
    from emprestimos e
    join livros l on l.id = e.livro_id
    where e.usuario_id = p_usuario_id and coalesce(l.categoria, '') <> ''
    group by lower(l.categoria)
    order by count(*) desc, lower(l.categoria) asc
    limit 1;

    select count(*) into v_avaliacoes from avaliacoes where usuario_id = p_usuario_id;
    select count(*) into v_favoritos from favoritos where usuario_id = p_usuario_id;

    select json_build_object(
            'emprestimo_id', e.id,
            'titulo', l.titulo,
            'data', e.data_prevista_devolucao,
            'dias_restantes', libro_data_local(e.data_prevista_devolucao) - hoje
        ) into v_proxima
    from emprestimos e
    join livros l on l.id = e.livro_id
    where e.usuario_id = p_usuario_id and e.status = 'ativo'
    order by e.data_prevista_devolucao asc
    limit 1;

    select json_build_object('motivo', s.motivo, 'data_fim', s.data_fim) into v_suspensao
    from suspensoes s
    where s.usuario_id = p_usuario_id and s.status = 'ativa' and s.data_fim >= hoje
    order by s.data_fim desc
    limit 1;

    select coalesce(json_agg(row_to_json(t)), '[]'::json) into v_historico
    from (
        select
            e.id, e.data_emprestimo, e.data_prevista_devolucao, e.data_devolucao_real,
            case when e.data_devolucao_real is null then null
                 else libro_data_local(e.data_devolucao_real) <= libro_data_local(e.data_prevista_devolucao)
            end as no_prazo,
            json_build_object('id', l.id, 'titulo', l.titulo, 'autor', l.autor, 'categoria', l.categoria, 'capa_url', l.capa_url) as livro,
            (select a.nota from avaliacoes a where a.usuario_id = e.usuario_id and a.livro_id = e.livro_id) as minha_nota
        from emprestimos e
        join livros l on l.id = e.livro_id
        where e.usuario_id = p_usuario_id and e.status = 'devolvido'
        order by e.data_devolucao_real desc nulls last
    ) t;

    return json_build_object(
        'usuario', json_build_object('id', u.id, 'nome', u.nome, 'email', u.email, 'tipo', u.tipo),
        'resumo', json_build_object(
            'totalEmprestimos', v_total,
            'lidos', v_lidos,
            'ativos', v_ativos,
            'atrasados', v_atrasados,
            'devolucoesNoPrazo', v_no_prazo,
            'categoriasDistintas', v_categorias,
            'avaliacoes', v_avaliacoes,
            'favoritos', v_favoritos,
            'pontualidade', case when v_devolvidos_com_data = 0 then null
                                 else round(v_no_prazo * 100.0 / v_devolvidos_com_data) end,
            'categoria_favorita', v_categoria_favorita
        ),
        'proxima_devolucao', v_proxima,
        'suspensao', v_suspensao,
        'historico', v_historico
    );
end;
$function$;


-- Avisos do topo da página inicial: suspensão, atraso, vencendo, reserva chegou
create or replace function public.alertas_usuario(p_usuario_id bigint)
 returns json
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
    hoje date;
    resultado json;
begin
    perform libro_manutencao();
    hoje := libro_hoje();

    select coalesce(json_agg(row_to_json(a) order by a.ordem, a.mensagem), '[]'::json) into resultado
    from (
        select 1 as ordem, 'suspensao' as tipo, 'erro' as nivel, '⛔' as icone,
               format('Sua conta está suspensa até %s. Nesse período não é possível pegar livros.',
                      to_char(s.data_fim, 'DD/MM/YYYY')) as mensagem,
               null::text as acao
        from suspensoes s
        where s.usuario_id = p_usuario_id and s.status = 'ativa' and s.data_fim >= hoje

        union all

        select 2, 'atraso', 'erro', '⚠️',
               format('"%s" está atrasado há %s dia(s). Devolva na biblioteca para evitar suspensão.',
                      l.titulo, hoje - libro_data_local(e.data_prevista_devolucao)),
               'emprestimos'
        from emprestimos e
        join livros l on l.id = e.livro_id
        where e.usuario_id = p_usuario_id and e.status = 'ativo'
        and libro_data_local(e.data_prevista_devolucao) < hoje

        union all

        select 3, 'vencendo', 'aviso', '⏳',
               format('"%s" vence %s. Renove ou devolva a tempo.', l.titulo,
                      case libro_data_local(e.data_prevista_devolucao) - hoje
                          when 0 then 'hoje'
                          when 1 then 'amanhã'
                          else 'em ' || (libro_data_local(e.data_prevista_devolucao) - hoje) || ' dias'
                      end),
               'emprestimos'
        from emprestimos e
        join livros l on l.id = e.livro_id
        where e.usuario_id = p_usuario_id and e.status = 'ativo'
        and libro_data_local(e.data_prevista_devolucao) between hoje and hoje + 3

        union all

        select 4, 'reserva', 'sucesso', '🔖',
               format('Sua reserva de "%s" chegou!%s', l.titulo,
                      case when r.data_disponivel is null then ''
                           else ' Retire até ' || to_char((r.data_disponivel + interval '48 hours') at time zone 'America/Sao_Paulo', 'DD/MM "às" HH24:MI') || '.'
                      end),
               'reservas'
        from reservas r
        join livros l on l.id = r.livro_id
        where r.usuario_id = p_usuario_id and r.status = 'disponivel'
    ) a;

    return resultado;
end;
$function$;


-- ---------------------------------------------------------------------
-- 6. FUNÇÕES NOVAS: PAINEL E BALCÃO DA BIBLIOTECA
-- ---------------------------------------------------------------------

create or replace function public.painel_biblioteca(p_solicitante_id bigint)
 returns json
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
    hoje date;
    v_indicadores json;
    v_por_mes json;
    v_por_categoria json;
    v_top_livros json;
    v_top_leitores json;
    v_atrasados json;
begin
    if not eh_bibliotecario(p_solicitante_id) then
        raise exception 'Acesso negado.';
    end if;

    perform libro_manutencao();
    hoje := libro_hoje();

    v_indicadores := json_build_object(
        'total_usuarios', (select count(*) from usuarios),
        'total_livros', (select count(*) from livros),
        'total_copias', (select coalesce(sum(quantidade_total), 0) from livros),
        'copias_disponiveis', (select coalesce(sum(greatest(quantidade_disponivel, 0)), 0) from livros),
        'emprestimos_ativos', (select count(*) from emprestimos where status = 'ativo'),
        'emprestimos_atrasados', (select count(*) from emprestimos
                                  where status = 'ativo' and libro_data_local(data_prevista_devolucao) < hoje),
        'total_emprestimos', (select count(*) from emprestimos),
        'reservas_na_fila', (select count(*) from reservas where status = 'ativa'),
        'pontualidade', (
            select case when count(*) = 0 then null
                        else round(100.0 * count(*) filter (
                                 where libro_data_local(data_devolucao_real) <= libro_data_local(data_prevista_devolucao)
                             ) / count(*))
                   end
            from emprestimos
            where status = 'devolvido' and data_devolucao_real is not null
        ),
        'media_avaliacoes', (select round(avg(nota)::numeric, 1) from avaliacoes),
        'total_avaliacoes', (select count(*) from avaliacoes)
    );

    -- últimos 6 meses, incluindo os meses sem nenhum empréstimo
    select json_agg(json_build_object(
                'mes', to_char(m, 'YYYY-MM'),
                'rotulo', (array['jan','fev','mar','abr','mai','jun','jul','ago','set','out','nov','dez'])[extract(month from m)::int]
                          || '/' || to_char(m, 'YY'),
                'total', (select count(*) from emprestimos e
                          where date_trunc('month', e.data_emprestimo at time zone 'America/Sao_Paulo') = m)
            ) order by m)
        into v_por_mes
    from generate_series(
        date_trunc('month', hoje::timestamp) - interval '5 months',
        date_trunc('month', hoje::timestamp),
        interval '1 month'
    ) as m;

    select coalesce(json_agg(row_to_json(t)), '[]'::json) into v_por_categoria
    from (
        select coalesce(nullif(lower(l.categoria), ''), 'sem categoria') as categoria, count(*)::int as total
        from emprestimos e
        join livros l on l.id = e.livro_id
        group by 1
        order by total desc
    ) t;

    select coalesce(json_agg(row_to_json(t)), '[]'::json) into v_top_livros
    from (
        select l.id, l.titulo, l.autor, count(*)::int as total
        from emprestimos e
        join livros l on l.id = e.livro_id
        group by l.id
        order by total desc, l.titulo asc
        limit 5
    ) t;

    select coalesce(json_agg(row_to_json(t)), '[]'::json) into v_top_leitores
    from (
        select u.id, u.nome, count(*)::int as total
        from emprestimos e
        join usuarios u on u.id = e.usuario_id
        group by u.id
        order by total desc, u.nome asc
        limit 5
    ) t;

    select coalesce(json_agg(row_to_json(t)), '[]'::json) into v_atrasados
    from (
        select
            e.id,
            json_build_object('id', u.id, 'nome', u.nome, 'email', u.email) as usuario,
            json_build_object('id', l.id, 'titulo', l.titulo) as livro,
            e.data_prevista_devolucao,
            hoje - libro_data_local(e.data_prevista_devolucao) as dias_atraso
        from emprestimos e
        join usuarios u on u.id = e.usuario_id
        join livros l on l.id = e.livro_id
        where e.status = 'ativo' and libro_data_local(e.data_prevista_devolucao) < hoje
        order by dias_atraso desc
    ) t;

    return json_build_object(
        'indicadores', v_indicadores,
        'emprestimos_por_mes', v_por_mes,
        'por_categoria', v_por_categoria,
        'top_livros', v_top_livros,
        'top_leitores', v_top_leitores,
        'atrasados', v_atrasados,
        'gerado_em', now()
    );
end;
$function$;


-- Empréstimo registrado pela biblioteca, no balcão, em nome de um aluno.
-- Usa as mesmas regras do pegar_emprestado (limite, suspensão, fila).
create or replace function public.emprestar_pelo_balcao(p_solicitante_id bigint, p_usuario_id bigint, p_livro_id bigint)
 returns json
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
    v_nome text;
    v_titulo text;
begin
    if not eh_bibliotecario(p_solicitante_id) then
        raise exception 'Acesso negado.';
    end if;

    select nome into v_nome from usuarios where id = p_usuario_id;
    if v_nome is null then
        raise exception 'Aluno não encontrado.';
    end if;
    select titulo into v_titulo from livros where id = p_livro_id;

