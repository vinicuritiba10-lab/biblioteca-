    perform registrar_log(p_solicitante_id, 'Empréstimo no balcão', format('%s para %s', v_titulo, v_nome));

    return json_build_object(
        'message', format('"%s" emprestado para %s. Devolução em 7 dias.', v_titulo, split_part(v_nome, ' ', 1))
    );
end;
$function$;

