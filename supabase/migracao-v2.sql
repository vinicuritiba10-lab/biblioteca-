-- Nota de 1 a 5 que o aluno dá a um livro que já pegou (uma por livro)
create table if not exists avaliacoes (
    id              bigint generated by default as identity primary key,
    usuario_id      bigint not null references usuarios(id) on delete cascade,
    livro_id        bigint not null references livros(id) on delete cascade,
    nota            integer not null check (nota between 1 and 5),
    comentario      text,
    data_avaliacao  timestamptz not null default now(),
    unique (usuario_id, livro_id)
);

-- Lista "Quero ler"
create table if not exists favoritos (
    id           bigint generated by default as identity primary key,
    usuario_id   bigint not null references usuarios(id) on delete cascade,
    livro_id     bigint not null references livros(id) on delete cascade,
    data_adicao  timestamptz not null default now(),
    unique (usuario_id, livro_id)
);

create index if not exists avaliacoes_livro_idx on avaliacoes (livro_id);
create index if not exists favoritos_usuario_idx on favoritos (usuario_id);

-- Igual às outras tabelas: RLS ligado e acesso só pelas funções abaixo
alter table avaliacoes enable row level security;
alter table favoritos enable row level security;

-- Quando a reserva ficou disponível (conta o prazo de 48h para retirar)
alter table reservas add column if not exists data_disponivel timestamptz;


