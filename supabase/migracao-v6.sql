CREATE OR REPLACE FUNCTION public.cadastrar_usuario(p_nome text, p_email text, p_senha text, p_tipo text, p_codigo text)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
AS $function$
declare
    novo_usuario usuarios;
    cod codigos_acesso;
    v_codigo text;
begin
    -- p_tipo continua na assinatura, mas é ignorado: toda conta nova é de aluno
    v_codigo := upper(regexp_replace(coalesce(p_codigo, ''), '[^A-Za-z0-9]', '', 'g'));

    select * into cod from codigos_acesso where codigo = v_codigo for update;
    if cod.id is null then
        raise exception 'Código de acesso inválido. Confira o código ou peça um novo na biblioteca.';
    end if;
    if cod.usado_em is not null then
        raise exception 'Este código de acesso já foi usado. Peça um novo na biblioteca.';
    end if;
    if cod.expira_em < now() then
        raise exception 'Este código de acesso expirou (ele vale 5 minutos). Peça um novo na biblioteca.';
    end if;

    if exists (select 1 from usuarios where email = p_email) then
        raise exception 'Este e-mail já está cadastrado.';
    end if;

    -- LGPD: o site só envia o cadastro depois do aceite da Política de Privacidade
    insert into usuarios (nome, email, senha, tipo, escola_id, aceite_privacidade_em)
    values (p_nome, p_email, extensions.crypt(p_senha, extensions.gen_salt('bf')), 'aluno', cod.escola_id, now())
    returning * into novo_usuario;

    update codigos_acesso set usado_em = now(), usado_por = novo_usuario.id where id = cod.id;

    perform registrar_log(novo_usuario.id, 'Cadastro realizado', 'Tipo: aluno; com código de acesso; aceitou a Política de Privacidade');

    return json_build_object(
        'id', novo_usuario.id,
        'nome', novo_usuario.nome,
        'email', novo_usuario.email,
        'tipo', novo_usuario.tipo,
        'escola_id', novo_usuario.escola_id
    );
end;
$function$;

CREATE OR REPLACE FUNCTION public.listar_escolas(p_solicitante_id bigint)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    resultado json;
    v_atual bigint;
begin
    if not eh_dono(p_solicitante_id) then
        raise exception 'Apenas a equipe Libro (dono) pode ver todas as escolas.';
    end if;
    v_atual := escola_do_usuario(p_solicitante_id);

    select coalesce(json_agg(row_to_json(t) order by t.nome), '[]'::json) into resultado
    from (
        select e.id, e.nome, e.cidade, e.criada_em,
               e.id = v_atual as atual,
               (select count(*) from usuarios u where u.escola_id = e.id and u.tipo = 'aluno')::int as alunos,
               (select count(*) from livros l where l.escola_id = e.id)::int as livros,
               (select count(*) from emprestimos em join livros l on l.id = em.livro_id
                 where l.escola_id = e.id and em.status = 'ativo')::int as emprestimos_ativos
        from escolas e
    ) t;
    return resultado;
end;
$function$;

CREATE OR REPLACE FUNCTION public.criar_escola(p_solicitante_id bigint, p_nome text, p_cidade text)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    nova escolas;
begin
    if not eh_dono(p_solicitante_id) then
        raise exception 'Apenas a equipe Libro (dono) pode cadastrar escolas.';
    end if;
    if coalesce(trim(p_nome), '') = '' then
        raise exception 'Informe o nome da escola.';
    end if;

    insert into escolas (nome, cidade) values (trim(p_nome), nullif(trim(coalesce(p_cidade, '')), ''))
    returning * into nova;

    perform registrar_log(p_solicitante_id, 'Escola cadastrada', nova.nome);

    return json_build_object('message', format('Escola "%s" cadastrada.', nova.nome), 'id', nova.id);
end;
$function$;

-- o dono "entra" numa escola: a partir daí, tudo o que ele vê e faz é dessa escola
CREATE OR REPLACE FUNCTION public.entrar_na_escola(p_solicitante_id bigint, p_escola_id bigint)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    esc escolas;
begin
    if not eh_dono(p_solicitante_id) then
        raise exception 'Apenas a equipe Libro (dono) pode trocar de escola.';
    end if;
    select * into esc from escolas where id = p_escola_id;
    if esc.id is null then
        raise exception 'Escola não encontrada.';
    end if;

    update usuarios set escola_id = esc.id where id = p_solicitante_id;
    perform registrar_log(p_solicitante_id, 'Dono entrou na escola', esc.nome);

    return json_build_object('message', format('Agora você está em: %s', esc.nome), 'escola_id', esc.id, 'escola_nome', esc.nome);
end;
$function$;


