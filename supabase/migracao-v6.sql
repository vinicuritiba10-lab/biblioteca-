-- agora recebe quem pede, para contar só os livros da escola dele
DROP FUNCTION IF EXISTS public.contagem_categorias();
CREATE OR REPLACE FUNCTION public.contagem_categorias(p_usuario_id bigint)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    resultado json;
begin
    select coalesce(json_agg(row_to_json(t)), '[]'::json) into resultado
    from (
        select lower(categoria) as categoria, count(*)::int as total
        from livros
        where coalesce(categoria, '') <> ''
          and escola_id = escola_do_usuario(p_usuario_id)
        group by lower(categoria)
        order by total desc
    ) t;
    return resultado;
end;
$function$;

CREATE OR REPLACE FUNCTION public.destaques_livros(p_usuario_id bigint)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    limite constant int := 8;
    v_escola bigint := escola_do_usuario(p_usuario_id);
    v_mais_emprestados json;
    v_bem_avaliados json;
    v_novidades json;
    v_recomendados json := '[]'::json;
    v_motivo text;
begin
    select coalesce(json_agg(row_to_json(t)), '[]'::json) into v_mais_emprestados
    from (
        select l.*, count(e.id)::int as total_emprestimos
        from livros l
        join emprestimos e on e.livro_id = l.id
        where l.escola_id = v_escola
        group by l.id
        order by total_emprestimos desc, l.titulo asc
        limit limite
    ) t;

    select coalesce(json_agg(row_to_json(t)), '[]'::json) into v_bem_avaliados
    from (
        select l.*, round(avg(a.nota)::numeric, 1) as media, count(a.id)::int as total_avaliacoes
        from livros l
        join avaliacoes a on a.livro_id = l.id
        where l.escola_id = v_escola
        group by l.id
        order by media desc, total_avaliacoes desc, l.titulo asc
        limit limite
    ) t;

    select coalesce(json_agg(row_to_json(t)), '[]'::json) into v_novidades
    from (
        select l.* from livros l where l.escola_id = v_escola order by l.id desc limit limite
    ) t;

    if p_usuario_id is not null then
        -- livros das categorias que o aluno mais lê e que ele ainda não pegou
        select coalesce(json_agg(row_to_json(t)), '[]'::json) into v_recomendados
        from (
            with categorias_do_aluno as (
                select lower(l.categoria) as categoria, count(*) as peso
                from emprestimos e
                join livros l on l.id = e.livro_id
                where e.usuario_id = p_usuario_id and coalesce(l.categoria, '') <> ''
                group by lower(l.categoria)
            ),
            popularidade as (
                select livro_id, count(*) as total from emprestimos group by livro_id
            )
            select l.*, coalesce(p.total, 0)::int as total_emprestimos
            from livros l
            join categorias_do_aluno c on lower(l.categoria) = c.categoria
            left join popularidade p on p.livro_id = l.id
            where l.escola_id = v_escola
              and l.id not in (select livro_id from emprestimos where usuario_id = p_usuario_id)
            order by c.peso desc, (l.quantidade_disponivel > 0) desc, coalesce(p.total, 0) desc, l.titulo asc
            limit limite
        ) t;
        v_motivo := 'Com base nas categorias que você mais lê';

        -- sem histórico: os mais populares que o aluno ainda não leu
        if json_array_length(v_recomendados) = 0 then
            select coalesce(json_agg(row_to_json(t)), '[]'::json) into v_recomendados
            from (
                select l.*, count(e.id)::int as total_emprestimos
                from livros l
                left join emprestimos e on e.livro_id = l.id
                where l.escola_id = v_escola
                  and l.id not in (select livro_id from emprestimos where usuario_id = p_usuario_id)
                group by l.id
                order by (l.quantidade_disponivel > 0) desc, total_emprestimos desc, l.id desc
                limit limite
            ) t;
            v_motivo := 'Populares que você ainda não leu';
        end if;
    end if;

    return json_build_object(
        'recomendados', json_build_object('motivo', v_motivo, 'livros', v_recomendados),
        'mais_emprestados', v_mais_emprestados,
        'bem_avaliados', v_bem_avaliados,
        'novidades', v_novidades
    );
end;
$function$;

CREATE OR REPLACE FUNCTION public.detalhes_livro(p_usuario_id bigint, p_livro_id bigint)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    liv livros;
    v_media numeric;
    v_total int;
    v_distribuicao json;
    v_recentes json;
    v_fila int;
    v_total_emprestimos int;
    v_usuario json;
    v_guardados int;
    v_reservado_ate timestamptz;
begin
    select * into liv from livros where id = p_livro_id;
    if liv.id is null or (p_usuario_id is not null and liv.escola_id is distinct from escola_do_usuario(p_usuario_id)) then
        raise exception 'Livro não encontrado.';
    end if;

    select round(avg(nota)::numeric, 1), count(*)::int into v_media, v_total
        from avaliacoes where livro_id = p_livro_id;

    select json_agg(json_build_object(
                'nota', n,
                'total', (select count(*) from avaliacoes where livro_id = p_livro_id and nota = n)
            ) order by n desc)
        into v_distribuicao
        from generate_series(1, 5) as n;

    select coalesce(json_agg(row_to_json(t)), '[]'::json) into v_recentes
    from (
        select a.id, a.usuario_id, coalesce(u.nome, 'Aluno') as nome, a.nota, a.comentario, a.data_avaliacao
        from avaliacoes a
        left join usuarios u on u.id = a.usuario_id
        where a.livro_id = p_livro_id
        order by a.data_avaliacao desc
        limit 20
    ) t;

    select count(*) into v_fila from reservas where livro_id = p_livro_id and status = 'ativa';
    select count(*) into v_total_emprestimos from emprestimos where livro_id = p_livro_id;

    select count(*)::int, min(data_disponivel) + interval '3 days'
        into v_guardados, v_reservado_ate
        from reservas
        where livro_id = p_livro_id and status = 'disponivel'
        and (p_usuario_id is null or usuario_id <> p_usuario_id);

    if p_usuario_id is not null then
        v_usuario := json_build_object(
            'favorito', exists (select 1 from favoritos where usuario_id = p_usuario_id and livro_id = p_livro_id),
            'pode_avaliar', exists (select 1 from emprestimos where usuario_id = p_usuario_id and livro_id = p_livro_id),
            'minha_avaliacao', (
                select row_to_json(x) from (
                    select id, nota, comentario from avaliacoes
                    where usuario_id = p_usuario_id and livro_id = p_livro_id
                ) x
            ),
            'emprestimo_ativo', (
                select row_to_json(x) from (
                    select id, data_prevista_devolucao from emprestimos
                    where usuario_id = p_usuario_id and livro_id = p_livro_id and status = 'ativo'
                    limit 1
                ) x
            ),
            'reserva', (
                select row_to_json(x) from (
                    select rr.id, rr.status, rr.data_disponivel,
                           rr.data_disponivel + interval '3 days' as retirar_ate,
                           (select count(*) from reservas r2
                             where r2.livro_id = rr.livro_id and r2.status = 'ativa'
                             and r2.data_reserva <= rr.data_reserva) as posicao
                    from reservas rr
                    where rr.usuario_id = p_usuario_id and rr.livro_id = p_livro_id and rr.status in ('ativa', 'disponivel')
                    limit 1
                ) x
            )
        );
    end if;

    return json_build_object(
        'livro', row_to_json(liv),
        'total_emprestimos', v_total_emprestimos,
        'fila_reservas', v_fila,
        'livres', greatest(liv.quantidade_disponivel - v_guardados, 0),
        'guardados', v_guardados,
        'reservado_ate', v_reservado_ate,
        'avaliacoes', json_build_object(
            'media', v_media,
            'total', v_total,
            'distribuicao', v_distribuicao,
            'recentes', v_recentes
        ),
        'usuario', v_usuario
    );
end;
$function$;

