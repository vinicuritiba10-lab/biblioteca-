CREATE OR REPLACE FUNCTION public.alterar_tipo_usuario(p_solicitante_id bigint, p_usuario_id bigint, p_novo_tipo text)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    alvo usuarios;
    v_dono boolean;
begin
    if not eh_admin(p_solicitante_id) then
        raise exception 'Apenas o administrador pode alterar o perfil de um usuário.';
    end if;
    v_dono := eh_dono(p_solicitante_id);

    if p_novo_tipo = 'admin' and not v_dono then
        raise exception 'Só a equipe Libro (dono) pode promover administradores.';
    end if;
    if p_novo_tipo not in ('aluno', 'bibliotecario', 'admin') then
        raise exception 'Tipo inválido. O perfil dono só pode ser definido direto no banco de dados.';
    end if;
    if p_usuario_id = p_solicitante_id then
        raise exception 'Você não pode alterar o seu próprio perfil.';
    end if;

    select * into alvo from usuarios where id = p_usuario_id;
    if alvo.id is null or alvo.escola_id is distinct from escola_do_usuario(p_solicitante_id) then
        raise exception 'Usuário não encontrado.';
    end if;
    if alvo.tipo = 'dono' then
        raise exception 'O perfil dono só pode ser alterado direto no banco de dados.';
    end if;
    if alvo.tipo = 'admin' and not v_dono then
        raise exception 'Só a equipe Libro (dono) pode alterar o perfil de um administrador.';
    end if;

    update usuarios set tipo = p_novo_tipo where id = p_usuario_id;

    perform registrar_log(p_solicitante_id, 'Tipo de usuário alterado', format('%s -> %s', alvo.nome, p_novo_tipo));

    return json_build_object('message', 'Tipo atualizado com sucesso.');
end;
$function$;

CREATE OR REPLACE FUNCTION public.deletar_usuario(p_solicitante_id bigint, p_usuario_id bigint)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    alvo usuarios;
begin
    if not eh_admin(p_solicitante_id) then
        raise exception 'Apenas o administrador pode excluir usuários.';
    end if;
    if p_solicitante_id = p_usuario_id then
        raise exception 'Você não pode deletar seu próprio usuário.';
    end if;

    select * into alvo from usuarios where id = p_usuario_id;
    if alvo.id is null or alvo.escola_id is distinct from escola_do_usuario(p_solicitante_id) then
        raise exception 'Usuário não encontrado.';
    end if;
    if alvo.tipo = 'dono' then
        raise exception 'Um dono só pode ser excluído direto no banco de dados.';
    end if;
    if alvo.tipo = 'admin' and not eh_dono(p_solicitante_id) then
        raise exception 'Só a equipe Libro (dono) pode excluir um administrador.';
    end if;

    delete from usuarios where id = p_usuario_id;

    perform registrar_log(p_solicitante_id, 'Usuário excluído', alvo.nome);

    return json_build_object('message', 'Usuário excluído com sucesso.');
exception
    when foreign_key_violation then
        raise exception 'Não é possível excluir: este usuário tem empréstimos ou reservas no histórico.';
end;
$function$;


