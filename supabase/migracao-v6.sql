CREATE OR REPLACE FUNCTION public.salvar_livro(p_solicitante_id bigint, p_livro_id bigint, p_titulo text, p_autor text, p_isbn text, p_editora text, p_ano integer, p_categoria text, p_quantidade_total integer, p_capa_url text, p_descricao text)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    v_escola bigint;
    livro_final livros;
    total_antigo int;
    disponivel_antigo int;
    novo_disponivel int;
begin
    v_escola := escola_da_equipe(p_solicitante_id);

    if p_livro_id is null then
        insert into livros (titulo, autor, isbn, editora, ano, categoria, quantidade_total, quantidade_disponivel, capa_url, descricao, escola_id)
        values (p_titulo, p_autor, p_isbn, p_editora, p_ano, p_categoria, p_quantidade_total, p_quantidade_total, p_capa_url, p_descricao, v_escola)
        returning * into livro_final;
    else
        select quantidade_total, quantidade_disponivel into total_antigo, disponivel_antigo
        from livros where id = p_livro_id and escola_id = v_escola;
        if not found then
            raise exception 'Livro não encontrado.';
        end if;

        novo_disponivel := greatest(0, disponivel_antigo + (p_quantidade_total - total_antigo));

        update livros set
            titulo = p_titulo,
            autor = p_autor,
            isbn = p_isbn,
            editora = p_editora,
            ano = p_ano,
            categoria = p_categoria,
            quantidade_total = p_quantidade_total,
            quantidade_disponivel = novo_disponivel,
            capa_url = p_capa_url,
            descricao = p_descricao
        where id = p_livro_id
        returning * into livro_final;
    end if;

    return row_to_json(livro_final);
end;
$function$;

CREATE OR REPLACE FUNCTION public.excluir_livro(p_solicitante_id bigint, p_livro_id bigint)
 RETURNS json
 LANGUAGE plpgsql
