CREATE OR REPLACE FUNCTION public.obter_estatisticas(p_solicitante_id bigint)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    v_escola bigint;
    v_total_usuarios int;
    v_total_livros int;
    v_emprestimos_ativos int;
    v_total_copias int;
    v_livros_emprestados int;
    v_copias_disponiveis int;
begin
    v_escola := escola_da_equipe(p_solicitante_id);

    select count(*) into v_total_usuarios from usuarios where escola_id = v_escola and tipo <> 'dono';
    select count(*) into v_total_livros from livros where escola_id = v_escola;
    select count(*) into v_emprestimos_ativos
        from emprestimos e join livros l on l.id = e.livro_id
        where e.status = 'ativo' and l.escola_id = v_escola;

    select coalesce(sum(quantidade_total), 0), coalesce(sum(quantidade_total - quantidade_disponivel), 0)
        into v_total_copias, v_livros_emprestados
        from livros where escola_id = v_escola;

    v_copias_disponiveis := greatest(v_total_copias - v_livros_emprestados, 0);

    return json_build_object(
        'total_usuarios', v_total_usuarios,
        'total_livros', v_total_livros,
        'emprestimos_ativos', v_emprestimos_ativos,
        'livros_emprestados', v_livros_emprestados,
        'total_copias', v_total_copias,
        'copias_disponiveis', v_copias_disponiveis,
        'data', now()
    );
end;
$function$;

CREATE OR REPLACE FUNCTION public.painel_biblioteca(p_solicitante_id bigint)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    v_escola bigint;
    hoje date;
    v_indicadores json;
    v_por_mes json;
    v_por_categoria json;
    v_top_livros json;
    v_top_leitores json;
    v_atrasados json;
begin
    v_escola := escola_da_equipe(p_solicitante_id);

    perform libro_manutencao();
    hoje := libro_hoje();

    v_indicadores := json_build_object(
        'total_usuarios', (select count(*) from usuarios where escola_id = v_escola and tipo <> 'dono'),
        'total_livros', (select count(*) from livros where escola_id = v_escola),
        'total_copias', (select coalesce(sum(quantidade_total), 0) from livros where escola_id = v_escola),
        'copias_disponiveis', (select coalesce(sum(greatest(quantidade_disponivel, 0)), 0) from livros where escola_id = v_escola),
        'emprestimos_ativos', (select count(*) from emprestimos e join livros l on l.id = e.livro_id
                               where e.status = 'ativo' and l.escola_id = v_escola),
        'emprestimos_atrasados', (select count(*) from emprestimos e join livros l on l.id = e.livro_id
                                  where e.status = 'ativo' and l.escola_id = v_escola
                                  and libro_data_local(e.data_prevista_devolucao) < hoje),
        'total_emprestimos', (select count(*) from emprestimos e join livros l on l.id = e.livro_id where l.escola_id = v_escola),
        'reservas_na_fila', (select count(*) from reservas r join livros l on l.id = r.livro_id
                             where r.status = 'ativa' and l.escola_id = v_escola),
        'pontualidade', (
            select case when count(*) = 0 then null
                        else round(100.0 * count(*) filter (
                                 where libro_data_local(e.data_devolucao_real) <= libro_data_local(e.data_prevista_devolucao)
                             ) / count(*))
                   end
            from emprestimos e join livros l on l.id = e.livro_id
            where e.status = 'devolvido' and e.data_devolucao_real is not null and l.escola_id = v_escola
        ),
        'media_avaliacoes', (select round(avg(a.nota)::numeric, 1) from avaliacoes a join livros l on l.id = a.livro_id where l.escola_id = v_escola),
        'total_avaliacoes', (select count(*) from avaliacoes a join livros l on l.id = a.livro_id where l.escola_id = v_escola)
    );

    -- últimos 6 meses, incluindo os meses sem nenhum empréstimo
    select json_agg(json_build_object(
                'mes', to_char(m, 'YYYY-MM'),
                'rotulo', (array['jan','fev','mar','abr','mai','jun','jul','ago','set','out','nov','dez'])[extract(month from m)::int]
                          || '/' || to_char(m, 'YY'),
                'total', (select count(*) from emprestimos e join livros l on l.id = e.livro_id
                          where l.escola_id = v_escola
                          and date_trunc('month', e.data_emprestimo at time zone 'America/Sao_Paulo') = m)
            ) order by m)
        into v_por_mes
    from generate_series(
        date_trunc('month', hoje::timestamp) - interval '5 months',
        date_trunc('month', hoje::timestamp),
        interval '1 month'
    ) as m;

    select coalesce(json_agg(row_to_json(t)), '[]'::json) into v_por_categoria
    from (
        select coalesce(nullif(lower(l.categoria), ''), 'sem categoria') as categoria, count(*)::int as total
        from emprestimos e
        join livros l on l.id = e.livro_id
        where l.escola_id = v_escola
        group by 1
        order by total desc
    ) t;

    select coalesce(json_agg(row_to_json(t)), '[]'::json) into v_top_livros
    from (
        select l.id, l.titulo, l.autor, count(*)::int as total
        from emprestimos e
        join livros l on l.id = e.livro_id
        where l.escola_id = v_escola
        group by l.id
        order by total desc, l.titulo asc
        limit 5
    ) t;

    select coalesce(json_agg(row_to_json(t)), '[]'::json) into v_top_leitores
    from (
        select u.id, u.nome, count(*)::int as total
        from emprestimos e
        join usuarios u on u.id = e.usuario_id
        join livros l on l.id = e.livro_id
        where l.escola_id = v_escola
        group by u.id
        order by total desc, u.nome asc
        limit 5
    ) t;

    select coalesce(json_agg(row_to_json(t)), '[]'::json) into v_atrasados
    from (
        select
            e.id,
            json_build_object('id', u.id, 'nome', u.nome, 'email', u.email) as usuario,
            json_build_object('id', l.id, 'titulo', l.titulo) as livro,
            e.data_prevista_devolucao,
            hoje - libro_data_local(e.data_prevista_devolucao) as dias_atraso
        from emprestimos e
        join usuarios u on u.id = e.usuario_id
        join livros l on l.id = e.livro_id
        where e.status = 'ativo' and l.escola_id = v_escola
        and libro_data_local(e.data_prevista_devolucao) < hoje
        order by dias_atraso desc
    ) t;

    return json_build_object(
        'indicadores', v_indicadores,
        'emprestimos_por_mes', v_por_mes,
        'por_categoria', v_por_categoria,
        'top_livros', v_top_livros,
        'top_leitores', v_top_leitores,
        'atrasados', v_atrasados,
        'gerado_em', now()
    );
end;
$function$;

