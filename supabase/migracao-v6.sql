CREATE OR REPLACE FUNCTION public.pegar_emprestado(p_usuario_id bigint, p_livro_id bigint)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    liv livros;
    total_ativos int;
    ja_tem_esse int;
    limite_maximo constant int := 2;
    fim_suspensao date;
    guardados_para_outros int;
begin
    select * into liv from livros where id = p_livro_id;
    if liv.id is null or liv.escola_id is distinct from escola_do_usuario(p_usuario_id) then
        raise exception 'Livro não encontrado.';
    end if;

    select data_fim into fim_suspensao from suspensoes
        where usuario_id = p_usuario_id and status = 'ativa' and data_fim >= libro_hoje()
        order by data_fim desc limit 1;
    if fim_suspensao is not null then
        raise exception 'Sua conta está suspensa até %. Nesse período não é possível pegar livros.', to_char(fim_suspensao, 'DD/MM/YYYY');
    end if;

    if liv.quantidade_disponivel <= 0 then
        raise exception 'Livro não disponível para empréstimo.';
    end if;

    -- exemplares guardados para quem está na frente da fila de reserva
    select count(*) into guardados_para_outros from reservas
        where livro_id = p_livro_id and status = 'disponivel' and usuario_id <> p_usuario_id;
    if liv.quantidade_disponivel <= guardados_para_outros then
        raise exception 'Este exemplar está guardado para quem reservou antes. Entre na fila de reserva.';
    end if;

    select count(*) into ja_tem_esse from emprestimos
        where usuario_id = p_usuario_id and livro_id = p_livro_id and status = 'ativo';
    if ja_tem_esse > 0 then
        raise exception 'Você já está com um exemplar deste livro emprestado.';
    end if;

    select count(*) into total_ativos from emprestimos
        where usuario_id = p_usuario_id and status = 'ativo';
    if total_ativos >= limite_maximo then
        raise exception 'Você já atingiu o limite de % livros emprestados ao mesmo tempo.', limite_maximo;
    end if;

    insert into emprestimos (usuario_id, livro_id, data_emprestimo, data_prevista_devolucao, status)
    values (p_usuario_id, p_livro_id, now(), now() + interval '7 days', 'ativo');

    update livros set quantidade_disponivel = quantidade_disponivel - 1 where id = p_livro_id;

    -- se o aluno tinha reserva desse livro, ela foi atendida
    update reservas set status = 'concluida', aviso_pendente = false
        where usuario_id = p_usuario_id and livro_id = p_livro_id and status in ('ativa', 'disponivel');

    perform registrar_log(p_usuario_id, 'Empréstimo realizado', liv.titulo);

    return json_build_object('message', 'Empréstimo realizado! Devolva em até 7 dias.');
end;
$function$;

