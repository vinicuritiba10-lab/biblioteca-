CREATE OR REPLACE FUNCTION public.login_usuario(p_email text, p_senha text)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
AS $function$
declare
    u usuarios;
    v_escola_nome text;
begin
    select * into u from usuarios where email = p_email;

    if u.id is null or u.senha != extensions.crypt(p_senha, u.senha) then
        raise exception 'E-mail ou senha inválidos.';
    end if;

    select nome into v_escola_nome from escolas where id = u.escola_id;

    perform registrar_log(u.id, 'Login realizado', null);

    return json_build_object(
        'id', u.id,
        'nome', u.nome,
        'email', u.email,
        'tipo', u.tipo,
        'escola_id', u.escola_id,
        'escola_nome', v_escola_nome
    );
end;
$function$;

CREATE OR REPLACE FUNCTION public.gerar_codigo_acesso(p_solicitante_id bigint)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
AS $function$
declare
    -- sem I, O, 0 e 1, que se confundem na hora de ditar o código
    alfabeto constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
    v_escola bigint;
    v_codigo text;
    v_expira timestamptz;
    v_escola_nome text;
    i int;
begin
    v_escola := escola_da_equipe(p_solicitante_id);

    -- limpeza: códigos vencidos e não usados há mais de um dia
    delete from codigos_acesso where usado_em is null and expira_em < now() - interval '1 day';

    loop
        v_codigo := '';
        for i in 1..6 loop
            v_codigo := v_codigo || substr(alfabeto, 1 + (get_byte(extensions.gen_random_bytes(1), 0) % 32), 1);
        end loop;
        exit when not exists (select 1 from codigos_acesso where codigo = v_codigo);
    end loop;

    v_expira := now() + interval '5 minutes';
    insert into codigos_acesso (codigo, escola_id, criado_por, expira_em)
    values (v_codigo, v_escola, p_solicitante_id, v_expira);

    select nome into v_escola_nome from escolas where id = v_escola;
    perform registrar_log(p_solicitante_id, 'Código de acesso gerado', 'Válido por 5 minutos');

    return json_build_object(
        'codigo', substr(v_codigo, 1, 3) || '-' || substr(v_codigo, 4, 3),
        'expira_em', v_expira,
        'escola_nome', v_escola_nome
    );
end;
$function$;

-- a versão antiga (sem código) deixa de existir: sem código não há cadastro
