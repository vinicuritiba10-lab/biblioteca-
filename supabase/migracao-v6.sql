CREATE OR REPLACE FUNCTION public.aplicar_suspensao(p_solicitante_id bigint, p_usuario_id bigint, p_emprestimo_id bigint, p_motivo text)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    v_escola bigint;
    usu usuarios;
    emp emprestimos;
    liv livros;
    dias_atraso int;
    data_fim_calc date;
    ja_existe int;
begin
    v_escola := escola_da_equipe(p_solicitante_id);

    select * into usu from usuarios where id = p_usuario_id and escola_id = v_escola;
    if usu.id is null then
        raise exception 'Usuário não encontrado.';
    end if;

    select * into emp from emprestimos where id = p_emprestimo_id;
    if emp.id is null then
        raise exception 'Empréstimo não encontrado.';
    end if;
    if emp.usuario_id <> p_usuario_id then
        raise exception 'Esse empréstimo não é desse aluno. Confira os números.';
    end if;

    select * into liv from livros where id = emp.livro_id;

    dias_atraso := greatest(1, ceil(extract(epoch from (now() - emp.data_prevista_devolucao)) / 86400));
    data_fim_calc := current_date + dias_atraso;

    select count(*) into ja_existe from suspensoes where usuario_id = p_usuario_id and status = 'ativa';
    if ja_existe > 0 then
        raise exception 'Este usuário já possui uma suspensão ativa.';
    end if;

    insert into suspensoes (usuario_id, emprestimo_id, motivo, dias_atraso, data_inicio, data_fim, status)
    values (
        p_usuario_id,
        p_emprestimo_id,
        coalesce(nullif(p_motivo, ''), 'Devolução em atraso: ' || coalesce(liv.titulo, 'livro')),
        dias_atraso,
        current_date,
        data_fim_calc,
        'ativa'
    );

    perform registrar_log(p_solicitante_id, 'Suspensão aplicada', format('Usuário: %s | %s dia(s)', usu.nome, dias_atraso));

    return json_build_object(
        'message', format('Usuário %s suspenso por %s dia(s).', usu.nome, dias_atraso),
        'usuario_email', usu.email,
        'usuario_nome', usu.nome,
        'livro_titulo', coalesce(liv.titulo, 'livro'),
        'dias_atraso', dias_atraso,
        'data_fim_suspensao', data_fim_calc
    );
end;
$function$;

