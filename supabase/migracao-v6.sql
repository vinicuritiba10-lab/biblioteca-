CREATE OR REPLACE FUNCTION public.aprovar_solicitacao(p_solicitante_id bigint, p_solicitacao_id bigint)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    v_escola bigint;
